//! WebAssembly bridge for `nirs4all-formats`.
//!
//! The browser context cannot call `std::fs::read`, so this binding exposes
//! byte-based entry points. Callers pass the file name (used to drive
//! extension-based sniffers) plus the file bytes, and optionally a map of
//! sidecar names → byte payloads for formats that need a companion file
//! (ENVI Standard, ENVI SLI, AVIRIS/ERDAS LAN, FGI XML+HDF5, NetCDF MFRSR).
//! The default WASM build enables the same reader families as the Rust facade:
//! HDF5/NetCDF-backed readers, MATLAB/RData, and Parquet, including
//! zstd-compressed Parquet pages.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use nirs4all_formats::{
    builtin_probes, export_targets as export_targets_native, open_bytes as open_bytes_native,
    open_with_sidecars as open_with_sidecars_native, plan_conversion as plan_conversion_native,
    reader_catalog as reader_catalog_native, sidecar_requirements as sidecar_requirements_native,
    write_records as write_records_native, AppliedConversion, InMemorySidecars, PlanOptions,
    SidecarResolver, SpectralRecord, WriteLoss, WriteOptions,
};
use serde::Serialize;
use serde_wasm_bindgen::Serializer;
use wasm_bindgen::prelude::*;

fn js_serializer() -> Serializer {
    // Produce plain JS objects (not Map). 64-bit integers are emitted as BigInt
    // rather than throwing: some readers carry u64/i64 metadata (Renishaw WDF and
    // TriVista TVF timestamps/IDs, etc.) that exceed Number.MAX_SAFE_INTEGER, and
    // the default serializer rejects those with "can't be represented as a
    // JavaScript number", failing the whole decode. On wasm32 `usize` is u32, so
    // shapes/indices stay plain numbers; only genuine 64-bit fields become BigInt.
    Serializer::new()
        .serialize_maps_as_objects(true)
        .serialize_large_number_types_as_bigints(true)
}

/// Serializer for export listings, plans and write reports: their JSON
/// integers (grid sizes, step parameters) are small and stay JS numbers.
fn export_serializer() -> Serializer {
    Serializer::new().serialize_maps_as_objects(true)
}

/// Decode an explicitly declared non-spectral PNG/VCF profile through the Rust owner.
#[wasm_bindgen(js_name = decodeMultimodalBytes)]
pub fn decode_multimodal_bytes(
    profile: &str,
    bytes: &[u8],
    max_decoded_bytes: u32,
) -> Result<JsValue, JsError> {
    nirs4all_formats::decode_multimodal_bytes(profile, bytes, max_decoded_bytes as usize)
        .map_err(|error| JsError::new(&error))?
        .serialize(&js_serializer())
        .map_err(|error| JsError::new(&error.to_string()))
}

#[wasm_bindgen(js_name = multimodalReaderCatalog)]
pub fn multimodal_reader_catalog() -> Result<JsValue, JsError> {
    nirs4all_formats::multimodal_reader_catalog()
        .serialize(&js_serializer())
        .map_err(|error| JsError::new(&error.to_string()))
}

#[wasm_bindgen(start)]
pub fn _start() {
    #[cfg(feature = "console-errors")]
    console_error_panic_hook::set_once();
}

/// Crate version exposed to JS.
#[wasm_bindgen(js_name = version)]
pub fn version() -> String {
    env!("CARGO_PKG_VERSION").to_string()
}

/// Feature flags the WASM build was compiled with. Useful for runtime checks
/// from JS ("does this WASM bundle have HDF5 support?").
///
/// The default browser build enables `fmt-hdf5`, `fmt-matlab`, and
/// `fmt-parquet`, including snappy, uncompressed, and zstd Parquet pages.
#[wasm_bindgen(js_name = features)]
pub fn features() -> Result<JsValue, JsError> {
    let flags = FeatureFlags {
        hdf5: cfg!(feature = "fmt-hdf5"),
        matlab: cfg!(feature = "fmt-matlab"),
        parquet: cfg!(feature = "fmt-parquet"),
    };
    flags
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Readers compiled into this WASM bundle.
///
/// This is intentionally generated by the Rust registry rather than duplicated
/// in JavaScript, so browser UIs can show the real format coverage of the
/// loaded bundle.
#[wasm_bindgen(js_name = readerCatalog)]
pub fn reader_catalog() -> Result<JsValue, JsError> {
    reader_catalog_native()
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Probe a file by name + bytes. Returns the ordered candidate readers.
///
/// The file name is required because several sniffers disambiguate by
/// extension (`.lan`, `.spc`, `.hdr`, ...). The first 8 KB of `bytes` is
/// inspected; pass the entire buffer or just the head — the implementation is
/// the same.
#[wasm_bindgen(js_name = probeBytes)]
pub fn probe_bytes(filename: &str, bytes: &[u8]) -> Result<JsValue, JsError> {
    let head_len = bytes.len().min(8192);
    let probes = builtin_probes(&bytes[..head_len], Path::new(filename));
    probes
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Return the sidecars declared by the matching format reader for this named
/// payload. The rules live inside each format module; this binding only
/// serializes them for browser UIs.
#[wasm_bindgen(js_name = sidecarRequirements)]
pub fn sidecar_requirements(filename: &str, bytes: &[u8]) -> Result<JsValue, JsError> {
    let requirements = sidecar_requirements_native(Path::new(filename), bytes);
    requirements
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Decode a file by name + bytes. Returns the spectral records as a JS array
/// matching the JSON shape produced by `nirs4all-formats read-json`.
///
/// Sidecar formats (ENVI Standard, AVIRIS LAN, FGI HDF5+XML, ...) return an
/// `UnsupportedSidecar` error here; use `openWithSidecars` instead.
/// Single-file HDF5 / NetCDF payloads decode directly through this entry
/// point now that `fmt-hdf5` is on.
#[wasm_bindgen(js_name = openBytes)]
pub fn open_bytes(filename: &str, bytes: &[u8]) -> Result<JsValue, JsError> {
    let records = open_bytes_native(Path::new(filename), bytes)
        .map_err(|err| JsError::new(&err.to_string()))?;
    records
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Decode a file by name + bytes plus a map of sidecar names → byte
/// payloads. Keys are relative path names (e.g. `"foo.hdr"` next to the
/// primary file). For the WASM build this powers ENVI Standard, ENVI SLI,
/// AVIRIS/ERDAS LAN and the HDF5-backed sidecar formats (FGI XML+HDF5,
/// NetCDF MFRSR with its QC YAML) now that `fmt-hdf5` is on.
#[wasm_bindgen(js_name = openWithSidecars)]
pub fn open_with_sidecars(
    filename: &str,
    bytes: &[u8],
    sidecars: JsValue,
) -> Result<JsValue, JsError> {
    let map: HashMap<String, Vec<u8>> = serde_wasm_bindgen::from_value(sidecars)
        .map_err(|err| JsError::new(&format!("sidecars must be an object of Uint8Array: {err}")))?;
    let mut resolver = InMemorySidecars::new();
    for (key, value) in map {
        resolver.insert(PathBuf::from(key), value);
    }
    let arc: Arc<dyn SidecarResolver> = Arc::new(resolver);
    let records = open_with_sidecars_native(Path::new(filename), bytes, arc)
        .map_err(|err| JsError::new(&err.to_string()))?;
    records
        .serialize(&js_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Export formats, software presets and the requirements of each format.
#[wasm_bindgen(js_name = exportTargets)]
pub fn export_targets() -> Result<JsValue, JsError> {
    export_targets_native()
        .serialize(&export_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Plan the conversions that make `records` writable for `target`.
///
/// `target` is a writer format or software preset, or `null`/`undefined` to
/// plan the options alone (for example `{ signal_type: "absorbance" }`).
/// Returns the plan: abstract steps naming the nirs4all-methods method that
/// computes each, questions to answer through the options, and refusals.
#[wasm_bindgen(js_name = planConversion)]
pub fn plan_conversion(
    records: JsValue,
    target: Option<String>,
    options: JsValue,
) -> Result<JsValue, JsError> {
    let records: Vec<SpectralRecord> = serde_wasm_bindgen::from_value(records)
        .map_err(|err| JsError::new(&format!("invalid records: {err}")))?;
    let options: PlanOptions = json_options(options, "plan options")?;
    let plan = plan_conversion_native(&records, target.as_deref(), &options)
        .map_err(|err| JsError::new(&err.to_string()))?;
    plan.serialize(&export_serializer())
        .map_err(|err| JsError::new(&err.to_string()))
}

/// Options object decoded through JSON, so unknown keys are refused.
fn json_options<T: serde::de::DeserializeOwned + Default>(
    options: JsValue,
    what: &str,
) -> Result<T, JsError> {
    if options.is_undefined() || options.is_null() {
        return Ok(T::default());
    }
    serde_wasm_bindgen::from_value::<serde_json::Value>(options)
        .map_err(|err| JsError::new(&format!("invalid {what}: {err}")))
        .and_then(|value| {
            serde_json::from_value(value)
                .map_err(|err| JsError::new(&format!("invalid {what}: {err}")))
        })
}

/// Write records to an export format or software preset.
///
/// `records` are the objects returned by `openBytes`; `options` is an object
/// with any of `signal`, `base_name`, `extension`, `axis_tolerance`, `multi`,
/// `delimiter` and `zip`. Returns `{ format, files: [{ name, media_type,
/// bytes }], losses, conversions }`.
#[wasm_bindgen(js_name = writeRecords)]
pub fn write_records(records: JsValue, target: &str, options: JsValue) -> Result<JsValue, JsError> {
    let records: Vec<SpectralRecord> = serde_wasm_bindgen::from_value(records)
        .map_err(|err| JsError::new(&format!("invalid records: {err}")))?;
    // Through a JSON value: struct decoding from JS skips unknown keys.
    let options: WriteOptions = json_options(options, "export options")?;
    let output = write_records_native(&records, target, &options)
        .map_err(|err| JsError::new(&err.to_string()))?;
    JsOutput {
        format: output.format,
        files: output
            .files
            .iter()
            .map(|file| JsFile {
                name: &file.name,
                media_type: file.media_type,
                bytes: JsBytes(&file.bytes),
            })
            .collect(),
        losses: &output.losses,
        conversions: &output.conversions,
    }
    .serialize(&export_serializer())
    .map_err(|err| JsError::new(&err.to_string()))
}

#[derive(Serialize)]
struct JsOutput<'a> {
    format: &'a str,
    files: Vec<JsFile<'a>>,
    losses: &'a [WriteLoss],
    conversions: &'a [AppliedConversion],
}

#[derive(Serialize)]
struct JsFile<'a> {
    name: &'a str,
    media_type: &'a str,
    bytes: JsBytes<'a>,
}

/// Serialized as a `Uint8Array`.
struct JsBytes<'a>(&'a [u8]);

impl Serialize for JsBytes<'_> {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_bytes(self.0)
    }
}

#[derive(Serialize)]
struct FeatureFlags {
    hdf5: bool,
    matlab: bool,
    parquet: bool,
}
